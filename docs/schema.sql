create or replace function public.get_site_analytics() returns jsonb language sql security definer set search_path=public as $$
with daily as (select visit_day,count(distinct visitor_id)::integer visitors,sum(page_views)::bigint page_views from public.site_visits where visit_day>=current_date-29 group by visit_day),
pages as (select path,sum(page_views)::bigint page_views from public.site_visits group by path order by page_views desc limit 10),
days as (select generate_series(current_date-29,current_date,interval '1 day')::date as day)
select jsonb_build_object('ok',true,'website',jsonb_build_object(
'unique_visitors_total',(select count(distinct visitor_id)::bigint from public.site_visits),
'unique_visitors_today',(select count(distinct visitor_id)::bigint from public.site_visits where visit_day=current_date),
'page_views_total',(select coalesce(sum(page_views),0)::bigint from public.site_visits),
'page_views_today',(select coalesce(sum(page_views),0)::bigint from public.site_visits where visit_day=current_date),
'daily',coalesce((select jsonb_agg(jsonb_build_object('day',days.day,'visitors',coalesce(daily.visitors,0),'page_views',coalesce(daily.page_views,0)) order by days.day) from days left join daily on daily.visit_day=days.day),'[]'::jsonb),
'top_pages',coalesce((select jsonb_agg(jsonb_build_object('path',pages.path,'page_views',pages.page_views) order by pages.page_views desc) from pages),'[]'::jsonb)));
$$;
revoke all on function public.get_site_analytics() from public;
grant execute on function public.get_site_analytics() to anon,authenticated;
